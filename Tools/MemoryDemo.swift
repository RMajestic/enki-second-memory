// Offline judge harness. All generated objects/descriptions below are SYNTHETIC.
// Executes the actual Second Memory store/query; never imports the private iOS host.
import Foundation
import Darwin

@main struct MemoryDemo {
    @MainActor static func main() async throws {
        let args = CommandLine.arguments
        guard args.count == 3, args[1] == "--new-synthetic-store" else {
            print("Usage: memory-demo --new-synthetic-store /absolute/NEW/test-directory")
            exit(2)
        }
        let path = args[2]
        guard path.hasPrefix("/"), !FileManager.default.fileExists(atPath: path) else {
            print("A new absolute directory is required; existing stores are never reused.")
            exit(2)
        }
        print("SYNTHETIC OFFLINE DEMO — NO CAMERA, META CALL, FACE ID OR REAL OBSERVATION")
        let store = ENKISecondMemoryStore(root: URL(fileURLWithPath: path), authorize: { true })
        let image = try Data(contentsOf: URL(fileURLWithPath: "Backend/SecondMemory/fixtures/synthetic-table.jpg"))
        func result(seconds: Double) throws -> ENKIRemoteVisualResult {
            let id = UUID().uuidString.lowercased()
            let timestamp = ISO8601DateFormatter().string(from: Date(timeIntervalSince1970: 1_793_700_000 + seconds))
            let row: [String: Any] = ["observation_id": id, "timestamp": timestamp,
                "scene_description": "SYNTHETIC TEST DESCRIPTION, not generated by Meta",
                "objects": [["label": "keys", "attributes": ["synthetic test"],
                             "location_in_scene": "fixture table — synthetic description", "confidence": NSNull()]],
                "uncertainties": ["Synthetic test oracle; no recognition or real Meta inference demonstrated"],
                "model_id": ENKIRemoteVisualResult.model, "source": "meta-model-api",
                "meta_request_id": "SYNTHETIC-HARNESS-NOT-PROVIDER-RESPONSE",
                "response_sha256": String(repeating: "a", count: 64),
                "usage": ["prompt_tokens": 0, "completion_tokens": 0, "estimated_usd": 0]]
            return try ENKIRemoteVisualResult.parse(JSONSerialization.data(withJSONObject: row), expectedID: id, timestamp: timestamp)
        }
        let older = try await store.save(image: image, result: result(seconds: 0), origin: .syntheticTest, explicitConsent: true)
        let newer = try await store.save(image: image, result: result(seconds: 60), origin: .syntheticTest, explicitConsent: true)
        let reopened = ENKISecondMemoryStore(root: URL(fileURLWithPath: path), authorize: { true })
        let listing = try await reopened.list()
        guard let last = ENKISecondMemoryQuery.lastKeys(in: listing.records), last.id == newer.id,
              try await reopened.evidence(last.id) == image else { fatalError("Synthetic evidence regression") }
        let output: [String: Any] = ["mode": "SYNTHETIC-OFFLINE-NOT-META-INFERENCE",
            "question": "Where did I last see my keys?", "origin": last.origin.rawValue,
            "captured_at": ISO8601DateFormatter().string(from: last.capturedAt),
            "location": try last.analysis().objects[0].location_in_scene,
            "evidence_sha256": last.imageSHA256, "evidence_matches_fixture": true,
            "limits": "Not current location, ownership, geolocation or physical glasses validation"]
        print(String(decoding: try JSONSerialization.data(withJSONObject: output, options: [.prettyPrinted, .sortedKeys]), as: UTF8.self))
        try await reopened.delete(older.id, explicitConsent: true)
        guard try await reopened.list().records.count == 1,
              try await reopened.evidence(newer.id) == image else { fatalError("Individual deletion regression") }
        try await reopened.delete(newer.id, explicitConsent: true)
        guard try await reopened.list().records.isEmpty else { fatalError("Deletion not persisted") }
        print("SYNTHETIC DEMO PASS: save → reopen → latest captured timestamp → exact evidence → individual delete")
        print("Only the newly created test directory remains; remove it manually if desired.")
    }
}
